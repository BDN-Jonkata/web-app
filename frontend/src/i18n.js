export function translate(language,key){
  if(language!=='en')return key==='welcome'?'Здравей! Питай ме за ВЕИ, потреблението или конкретен град.\n\nМога и да управлявам симулацията — опитай „покажи зима вечер“.':key;
  if(en[key])return en[key];
  if(typeof key==='string'&&key.startsWith('общ. '))return 'Municipality: '+translate(language,key.slice(5));
  if(typeof key==='string'&&key.includes(', '))return key.split(', ').map(part=>en[part]||part).join(', ');
  return key;
}
export const formatNumber=(value,language)=>Math.round(value).toLocaleString(language==='en'?'en-GB':'bg-BG');
export function errorText(error,language) {
  if(['AI_RATE_LIMIT','CHAT_RATE_LIMIT'].includes(error?.code))return language==='en'?'Request limit reached. Please wait and try again.':'Достигнат е лимитът на заявките. Изчакай и опитай отново.';
  return errors[error?.code]?.[language==='en'?1:0]||translate(language,error?.message||'Входът не е завършен.');
}
